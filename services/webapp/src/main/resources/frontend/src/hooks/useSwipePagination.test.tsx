import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import { useState } from 'react';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { useSwipePagination } from './useSwipePagination';

function touch(clientX: number, clientY = 100, identifier = 1) {
  return { clientX, clientY, identifier };
}

function Surface({ enabled = true, initialPage = 2, onClick = vi.fn() }) {
  const [page, setPage] = useState(initialPage);
  const handlers = useSwipePagination({ enabled, page, pageCount: 3, onPageChange: setPage });
  return <div data-testid="apps" {...handlers}>
    <output>{page}</output>
    <button type="button" onClick={onClick}>App</button>
    <input aria-label="Installer" />
  </div>;
}

function swipe(target: HTMLElement, from = touch(200), to = touch(100)) {
  fireEvent.touchStart(target, { touches: [from] });
  fireEvent.touchMove(target, { touches: [to] });
  fireEvent.touchEnd(target, { touches: [], changedTouches: [to] });
}

describe('useSwipePagination', () => {
  afterEach(cleanup);

  it('advances left and goes back right, one page per gesture', () => {
    render(<Surface />);
    const apps = screen.getByTestId('apps');
    swipe(apps);
    expect(screen.getByRole('status')).toHaveTextContent('3');
    swipe(apps, touch(100), touch(200));
    expect(screen.getByRole('status')).toHaveTextContent('2');
  });

  it.each([
    { initialPage: 1, from: 100, to: 200 },
    { initialPage: 3, from: 200, to: 100 },
  ])('keeps page $initialPage at the pagination boundary', ({ initialPage, from, to }) => {
    render(<Surface initialPage={initialPage} />);
    swipe(screen.getByTestId('apps'), touch(from), touch(to));
    expect(screen.getByRole('status')).toHaveTextContent(String(initialPage));
  });

  it.each([
    { name: 'a tap', to: touch(200) },
    { name: 'a short drag', to: touch(170) },
    { name: 'vertical scrolling', to: touch(190, 220) },
    { name: 'a diagonal drag', to: touch(100, 180) },
  ])('ignores $name', ({ to }) => {
    render(<Surface />);
    swipe(screen.getByTestId('apps'), touch(200), to);
    expect(screen.getByRole('status')).toHaveTextContent('2');
  });

  it('does not turn a vertical scroll into pagination when the finger later moves sideways', () => {
    render(<Surface />);
    const apps = screen.getByTestId('apps');
    fireEvent.touchStart(apps, { touches: [touch(200)] });
    fireEvent.touchMove(apps, { touches: [touch(195, 140)] });
    fireEvent.touchEnd(apps, { touches: [], changedTouches: [touch(50, 145)] });
    expect(screen.getByRole('status')).toHaveTextContent('2');
  });

  it('ignores multi-touch, interrupted gestures and a different finger', () => {
    render(<Surface />);
    const apps = screen.getByTestId('apps');
    fireEvent.touchStart(apps, { touches: [touch(200), touch(210, 100, 2)] });
    fireEvent.touchEnd(apps, { touches: [], changedTouches: [touch(100)] });
    fireEvent.touchStart(apps, { touches: [touch(200)] });
    fireEvent.touchMove(apps, { touches: [touch(180), touch(210, 100, 2)] });
    fireEvent.touchEnd(apps, { touches: [], changedTouches: [touch(100)] });
    fireEvent.touchStart(apps, { touches: [touch(200)] });
    fireEvent.touchCancel(apps);
    fireEvent.touchEnd(apps, { touches: [], changedTouches: [touch(100)] });
    fireEvent.touchStart(apps, { touches: [touch(200)] });
    fireEvent.touchEnd(apps, { touches: [], changedTouches: [touch(100, 100, 2)] });
    expect(screen.getByRole('status')).toHaveTextContent('2');
  });

  it('leaves desktop and form controls alone', () => {
    const { rerender } = render(<Surface enabled={false} />);
    swipe(screen.getByTestId('apps'));
    expect(screen.getByRole('status')).toHaveTextContent('2');
    rerender(<Surface />);
    swipe(screen.getByRole('textbox'));
    expect(screen.getByRole('status')).toHaveTextContent('2');
  });

  it('suppresses the click generated by a swipe but preserves taps and keyboard activation', () => {
    const onClick = vi.fn();
    render(<Surface onClick={onClick} />);
    const button = screen.getByRole('button');
    swipe(button);
    fireEvent.click(button, { detail: 1 });
    expect(onClick).not.toHaveBeenCalled();
    fireEvent.click(button, { detail: 0 });
    expect(onClick).toHaveBeenCalledTimes(1);
    swipe(button, touch(200), touch(200));
    fireEvent.click(button, { detail: 1 });
    expect(onClick).toHaveBeenCalledTimes(2);
  });
});
